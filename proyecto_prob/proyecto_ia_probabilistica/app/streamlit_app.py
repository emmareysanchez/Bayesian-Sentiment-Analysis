st.set_page_config(page_title="Bayesian Sentiment", page_icon="🧠", layout="wide")
st.title("🧠 Bayesian Sentiment Analyzer")
st.caption("Monteagudo & Rey — MUIA 2025/2026 · IA Probabilística")
st.caption(f"Running on: {DEVICE}")

with st.sidebar:
    st.header("Model")
    available_models = _available_models()
    if not available_models:
        st.error("No trained models found. Run the training pipeline first.")
        st.stop()

    selected_model = st.selectbox("Architecture", available_models, index=0)

    seeds = _available_seeds(MODELS_ROOT / selected_model)
    best = _best_seed(selected_model)
    seed_options = ["Auto (best accuracy)"] + seeds
    seed_choice = st.selectbox("Seed", seed_options, index=0)

    if seed_choice == "Auto (best accuracy)":
        resolved_seed = best if best and best in seeds else seeds[0]
        if best:
            st.caption(f"Best seed by test accuracy: **{resolved_seed}**")
    else:
        resolved_seed = seed_choice

    bundle = load_model(selected_model, resolved_seed, str(DEVICE))
    if bundle is None:
        st.error(f"Could not load {selected_model} / {resolved_seed}")
        st.stop()

    bayesian = bundle["kind"] != "deterministic"
    st.info(f"Loaded: **{bundle['name']}** · {resolved_seed}")
    st.write(f"Bayesian: {bayesian} · Topic gating: {bundle.get('use_theta', False)}")

    st.divider()
    st.header("Sampling")
    default_mc = 20 if bayesian else 1
    mc_samples = st.slider("MC samples", 1, 100, default_mc, step=1)
    st.caption("More samples = more stable uncertainty, but slower.")

    st.divider()
    st.header("Decision rule")
    if bayesian:
        score_name = st.selectbox(
            "Uncertainty score for abstention",
            ["mutual_info", "predictive_entropy"],
            index=0,
        )
        max_tau = 0.693 if score_name == "predictive_entropy" else 0.35
        default_tau = 0.05 if score_name == "mutual_info" else 0.40
    else:
        score_name = "predictive_entropy"
        max_tau = 0.693
        default_tau = 0.40

    tau = st.slider("Rejection threshold τ", 0.0, float(max_tau), float(default_tau), step=0.005)
    st.caption("Higher τ → model abstains less often")

    if bundle.get("use_theta"):
        vec_type = _slda_vectorizer_type()
        st.caption(f"sLDA vectorizer: **{vec_type}**")

tok, bert = load_bert(str(DEVICE))
slda, vec = load_slda() if bundle.get("use_theta") else (None, None)

example_options, example_records = _load_examples()
example_choice = st.selectbox("Predefined example", list(example_options.keys()), index=0)
selected_example = example_records.get(example_choice)
default_text = example_options[example_choice]
text = st.text_area(
    "Review text",
    value=default_text,
    height=180,
    placeholder="Paste a movie review here...",
)

if selected_example is not None:
    expected = _example_expected_label(selected_example)
    if expected is not None:
        st.caption(f"Expected label for this predefined example: **{expected}**")

if st.button("Analyze", type="primary"):
    use_precomputed = False
    pre_emb = None
    pre_theta = None
    if selected_example is not None and text.strip() == selected_example.get("text", "").strip():
        if "embedding" in selected_example:
            pre_emb = np.asarray(selected_example["embedding"], dtype=np.float32)
            pre_theta = np.asarray(selected_example["theta"], dtype=np.float32) if "theta" in selected_example else None
            use_precomputed = True

    with st.spinner("Running predictions..."):
        out = predict(
            text,
            bundle,
            tok,
            bert,
            slda=slda,
            vec=vec,
            mc_samples=mc_samples,
            precomputed_emb=pre_emb,
            precomputed_theta=pre_theta,
        )

    p_neg = float(out["mean_probs"][0])
    p_pos = float(out["mean_probs"][1])
    H = out["predictive_entropy"]
    H_ale = out["aleatoric_entropy"]
    MI = out["mutual_info"]
    score_value = MI if score_name == "mutual_info" else H

    decision = "🙋 ABSTAIN (human review)" if score_value > tau else ("😊 POSITIVE" if p_pos >= p_neg else "😞 NEGATIVE")

    st.subheader("Prediction")
    c1, c2, c3 = st.columns(3)
    c1.metric("p(negative)", f"{p_neg:.3f}")
    c2.metric("p(positive)", f"{p_pos:.3f}")
    c3.metric("Decision", decision)

    if use_precomputed:
        st.caption("Used cached embedding/theta from example_reviews.json for this predefined example.")
    elif selected_example is not None:
        st.caption("The text was edited or the example has no cached features, so it was re-encoded online.")

    if score_value > tau:
        st.warning(f"{score_name} = {score_value:.3f} > τ = {tau:.3f}. Routing to human review.")
    else:
        st.success(f"{score_name} = {score_value:.3f} ≤ τ = {tau:.3f}. Auto-classify.")

    st.subheader("Uncertainty")
    if bayesian:
        d1, d2, d3 = st.columns(3)
        d1.metric("Predictive entropy H[ȳ]", f"{H:.4f}")
        d2.metric("Aleatoric E[H(p)]", f"{H_ale:.4f}")
        d3.metric("Epistemic MI", f"{MI:.4f}")
    else:
        st.metric("Predictive entropy", f"{H:.4f}")
        st.caption("Deterministic model — no epistemic/aleatoric decomposition available.")

    if out["theta"] is not None:
        st.subheader("Topic mixture θ (sLDA)")
        try:
            with open(SLDA_DIR / "topic_words.json", encoding="utf-8") as f:
                tw = json.load(f)
            with open(SLDA_DIR / "topic_sentiment.json", encoding="utf-8") as f:
                ts = json.load(f)
        except Exception:
            tw, ts = {}, {}
        theta = out["theta"]
        top3 = np.argsort(theta)[::-1][:3]
        for k in top3:
            words = " ".join(tw.get(str(int(k)), [])[:8])
            sent = float(ts.get(str(int(k)), 0.0))
            tag = "POS" if sent > 0.1 else ("NEG" if sent < -0.1 else "neu")
            st.write(f"- **Topic {int(k)}** ({theta[k] * 100:.1f}%, {tag} {sent:+.2f}): _{words}_")

    with st.expander("Raw output"):
        st.json({
            "mean_probs": out["mean_probs"].tolist(),
            "predictive_entropy": H,
            "aleatoric_entropy": H_ale,
            "mutual_info": MI,
            "decision_score": score_name,
            "decision_value": score_value,
            "mc_samples": out["mc_samples_count"],
        })
