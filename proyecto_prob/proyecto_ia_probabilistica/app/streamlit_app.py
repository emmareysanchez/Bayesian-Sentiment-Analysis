def _load_examples() -> tuple[dict[str, str], dict[str, dict[str, Any]]]:
    options = {"— write your own —": ""}
    records: dict[str, dict[str, Any]] = {}
    if not EXAMPLES_PATH.exists():
        return options, records

    try:
        data = json.loads(EXAMPLES_PATH.read_text(encoding="utf-8"))
        for label_key, label_name in [("positive", "Positive"), ("negative", "Negative")]:
            for i, e in enumerate(data.get(label_key, []), 1):
                h = e.get("max_entropy", e.get("mean_entropy", 0.0))
                key = f"{label_name} example {i}  (worst H={h:.3f})"
                options[key] = e["text"]
                records[key] = e
    except Exception:
        pass
    return options, records


def _example_expected_label(example_record: dict[str, Any] | None) -> str | None:
    if example_record is None or "label" not in example_record:
        return None
    return "POSITIVE" if int(example_record["label"]) == 1 else "NEGATIVE"


