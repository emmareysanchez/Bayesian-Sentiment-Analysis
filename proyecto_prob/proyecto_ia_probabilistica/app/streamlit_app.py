@st.cache_resource
def load_bert(device_str: str):
    from transformers import DistilBertModel, DistilBertTokenizer

    device = torch.device(device_str)
    tok = DistilBertTokenizer.from_pretrained("distilbert-base-uncased")
    model = DistilBertModel.from_pretrained("distilbert-base-uncased")
    model.eval()
    model.to(device)
    return tok, model


def _slda_vectorizer_type() -> str:
    meta_path = SLDA_DIR / "slda_meta.json"
    if meta_path.exists():
        with open(meta_path, encoding="utf-8") as f:
            return json.load(f).get("vectorizer", "bow")
    if (SLDA_DIR / "lda.pkl").exists():
        return "bow"
    return "bow"


@st.cache_resource
def load_slda():
    if not (SLDA_DIR / "lda.pkl").exists():
        return None, None
    slda = AmortizedSLDA.load(SLDA_DIR, device="cpu")
    vec_type = _slda_vectorizer_type()
    if vec_type == "tfidf":
        _, vec = load_tfidf()
    else:
        _, vec = load_bow()
    return slda, vec


@st.cache_resource
def load_model(name: str, seed_name: str, device_str: str):
    device = torch.device(device_str)
    seed_dir = MODELS_ROOT / name / seed_name
    if not seed_dir.exists():
        return None

    if name in ("deterministic", "mc_dropout"):
        ck = torch.load(seed_dir / "state.pt", map_location="cpu", weights_only=False)
        input_dim = ck["input_dim"]
        if name == "deterministic":
            model = DeterministicMLP(input_dim=input_dim)
        else:
            model = MCDropoutMLP(input_dim=input_dim, dropout_p=ck.get("dropout_p", 0.2))
        model.load_state_dict(ck["state"])
        model.eval()
        model.to(device)
        scaler = Standardizer(ck["scaler_mean"], ck["scaler_std"])
        return {
            "name": name,
            "seed": seed_name,
            "kind": name,
            "model": model,
            "guide": None,
            "scaler": scaler,
            "use_theta": False,
            "device": device,
        }

    meta = torch.load(seed_dir / "meta.pt", map_location="cpu", weights_only=False)
    cfg = BayesianMoEConfig(**meta["cfg"])
    pyro.clear_param_store()
    state = torch.load(seed_dir / "pyro_store.pt", map_location=device, weights_only=False)
    pyro.get_param_store().set_state(state)
    model = BayesianMoE(cfg)
    model.to(device)
    guide = AutoNormal(model)
    dummy_x = torch.zeros(2, cfg.input_dim, device=device)
    dummy_y = torch.zeros(2, dtype=torch.long, device=device)
    if meta["use_theta"]:
        dummy_th = torch.ones(2, cfg.n_experts, device=device) / cfg.n_experts
        guide(dummy_x, dummy_th, dummy_y)
    else:
        guide(dummy_x, None, dummy_y)
    scaler = Standardizer(meta["scaler_mean"], meta["scaler_std"])
    param_snapshot = {k: v.detach().clone() for k, v in pyro.get_param_store().items()}
    return {
        "name": name,
        "seed": seed_name,
        "kind": "bnn",
        "model": model,
        "guide": guide,
        "scaler": scaler,
        "use_theta": bool(meta["use_theta"]),
        "cfg": cfg,
        "device": device,
        "_param_snapshot": param_snapshot,
    }


# -----------------------------
# Inference
# -----------------------------

def encode_text(text: str, tok, bert, device: torch.device) -> np.ndarray:
    text = clean_text(text)
    if not text.strip():
        text = "[UNK]"
    enc = tok([text], truncation=True, padding=True, max_length=256, return_tensors="pt")
    enc = {k: v.to(device) for k, v in enc.items()}
    with torch.inference_mode():
        h = bert(**enc).last_hidden_state[:, 0, :]
    return h.detach().cpu().float().numpy()


def theta_for_text(text: str, slda, vec) -> np.ndarray | None:
    if slda is None or vec is None:
        return None
    cleaned = clean_text(text) or "[UNK]"
    X = vec.transform([cleaned])
    return slda.theta(X)


def predict(
    text: str,
    bundle: dict,
    tok,
    bert,
    slda=None,
    vec=None,
    mc_samples: int = 20,
    precomputed_emb: np.ndarray | None = None,
    precomputed_theta: np.ndarray | None = None,
):
    device = bundle["device"]
    emb = precomputed_emb if precomputed_emb is not None else encode_text(text, tok, bert, device)
    emb = np.asarray(emb, dtype=np.float32)
    if emb.ndim == 1:
        emb = emb[np.newaxis, :]

    emb_t_cpu = torch.tensor(emb, dtype=torch.float32)
    emb_std = bundle["scaler"].transform(emb_t_cpu).to(device)

    theta_np = None
    if bundle.get("use_theta"):
        if precomputed_theta is not None:
            theta_np = np.asarray(precomputed_theta, dtype=np.float32)
            if theta_np.ndim == 1:
                theta_np = theta_np[np.newaxis, :]
        else:
            theta_np = theta_for_text(text, slda, vec)
            if theta_np is None:
                n_exp = bundle["cfg"].n_experts
                theta_np = np.ones((1, n_exp), dtype=np.float32) / n_exp
        theta_t = torch.tensor(theta_np, dtype=torch.float32, device=device)
    else:
        theta_t = None

    if bundle["kind"] == "deterministic":
        with torch.inference_mode():
            probs = torch.softmax(bundle["model"](emb_std), dim=-1)
        mc = probs.unsqueeze(0)
    elif bundle["kind"] == "mc_dropout":
        with torch.inference_mode():
            logits = bundle["model"].mc_forward(emb_std, mc_samples=mc_samples)
            mc = torch.softmax(logits, dim=-1)
    else:
        if "_param_snapshot" in bundle:
            pyro.clear_param_store()
            for k, v in bundle["_param_snapshot"].items():
                pyro.get_param_store()[k] = v.detach().clone()
        predictive = pyro.infer.Predictive(
            bundle["model"],
            guide=bundle["guide"],
            num_samples=mc_samples,
            return_sites=("_RETURN",),
        )
        if theta_t is not None:
            logits = predictive(emb_std, theta_t)["_RETURN"]
        else:
            logits = predictive(emb_std)["_RETURN"]
        mc = torch.softmax(logits, dim=-1)

    decomp = decompose_mc(mc)
    return {
        "mean_probs": mc.mean(0).squeeze(0).detach().cpu().numpy(),
        "predictive_entropy": float(decomp["predictive_entropy"].item()),
        "aleatoric_entropy": float(decomp["aleatoric_entropy"].item()),
        "mutual_info": float(decomp["mutual_info"].item()),
        "theta": theta_np[0] if theta_np is not None else None,
        "mc_samples_count": int(mc.shape[0]),
    }


